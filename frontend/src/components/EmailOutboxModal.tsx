import React, { useState, useEffect } from 'react';
import api from '../api/client';
import { SimulatedEmail } from '../types';
import { X, Mail, RefreshCw, CheckCircle2 } from 'lucide-react';

interface EmailOutboxModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const EmailOutboxModal: React.FC<EmailOutboxModalProps> = ({ isOpen, onClose }) => {
  const [emails, setEmails] = useState<SimulatedEmail[]>([]);
  const [loading, setLoading] = useState(false);

  const fetchEmails = async () => {
    setLoading(true);
    try {
      const res = await api.get('/simulator/emails');
      setEmails(res.data.data || []);
    } catch (err) {
      console.error('Failed to load simulated emails:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      fetchEmails();
    }
  }, [isOpen]);

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-zinc-950/40 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="bg-white rounded-2xl shadow-2xl border border-zinc-200/90 w-full max-w-2xl max-h-[85vh] flex flex-col overflow-hidden">
        {/* Header */}
        <div className="px-6 py-3.5 border-b border-zinc-100 flex items-center justify-between bg-zinc-50/50">
          <div>
            <h2 className="text-sm font-semibold text-zinc-900 tracking-tight">Outbound Notification Dispatcher</h2>
            <p className="text-[11px] text-zinc-500 mt-0.5">
              Simulated customer emails generated by asynchronous event listeners
            </p>
          </div>
          <div className="flex items-center gap-1">
            <button
              onClick={fetchEmails}
              disabled={loading}
              className="p-1.5 text-zinc-400 hover:text-zinc-700 rounded-md hover:bg-zinc-100 transition-colors"
              title="Refresh outbox"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
            </button>
            <button
              onClick={onClose}
              className="p-1.5 text-zinc-400 hover:text-zinc-700 rounded-md hover:bg-zinc-100 transition-colors"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Content list */}
        <div className="flex-1 overflow-y-auto p-5 space-y-3">
          {emails.length === 0 ? (
            <div className="p-10 text-center text-zinc-400 text-xs">
              <Mail className="w-6 h-6 mx-auto mb-2 text-zinc-300 stroke-[1.5]" />
              <p>No outbound emails recorded in this session.</p>
            </div>
          ) : (
            emails.map((email) => (
              <div
                key={email.id}
                className="p-3.5 rounded-xl border border-zinc-200/80 bg-zinc-50/40 space-y-1.5"
              >
                <div className="flex items-center justify-between text-[11px]">
                  <span className="font-medium text-zinc-800 flex items-center gap-1.5">
                    <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                    To: {email.to}
                  </span>
                  <span className="text-zinc-400 font-mono">
                    {new Date(email.sentAt).toLocaleTimeString()}
                  </span>
                </div>
                <p className="text-xs font-semibold text-zinc-900">{email.subject}</p>
                <div className="p-2.5 bg-white rounded-lg border border-zinc-200/70 text-xs text-zinc-600 whitespace-pre-wrap font-mono leading-relaxed">
                  {email.body}
                </div>
              </div>
            ))
          )}
        </div>

        <div className="px-5 py-2.5 border-t border-zinc-100 bg-zinc-50/50 flex items-center justify-between text-xs text-zinc-500">
          <span>{emails.length} notifications dispatched</span>
          <button
            onClick={onClose}
            className="px-3 py-1 text-xs text-zinc-700 hover:bg-zinc-200 rounded-md"
          >
            Dismiss
          </button>
        </div>
      </div>
    </div>
  );
};
